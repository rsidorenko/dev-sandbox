#!/bin/sh
# setup_letsencrypt_autorenew.sh
#
# One-time operator setup of host-level Let's Encrypt (certbot) for bravada-connect.ru
# with automatic renewal that keeps nginx's cert files fresh.
#
# WHY THIS EXISTS
# The Docker `certbot` service in docker-compose.prod.yml renews into a named volume
# (`certs:/etc/letsencrypt`) that nginx does NOT read — nginx reads `/opt/bravada/ssl/`.
# So that service is effectively dead and the cert in `ssl/` is rotated manually.
# A manual cert silently expires (LE = 90 days). This script installs a proper host-level
# certbot whose renew-hook syncs the renewed cert into `/opt/bravada/ssl/` and reloads
# nginx, so renewal is automatic and actually reaches nginx.
#
# This uses DV (domain-validation) Let's Encrypt certs — NOT subject to the GlobalSign
# sanctions-driven revocation wave (OV/EV only). See backend/docs/ssl_autorenew_runbook.md.
#
# Run ONCE on the production host as root (or via sudo). Idempotent — safe to re-run.
#
# Usage:
#   sudo ./backend/scripts/setup_letsencrypt_autorenew.sh \
#       --domain bravada-connect.ru \
#       --webroot /opt/bravada/certbot-www
#
# Prereq: nginx must serve `/.well-known/acme-challenge/` from the host path passed as
# --webroot. The shipped nginx config serves it from the container path /var/www/certbot
# (the `certbot-www` volume). To make that path host-accessible, bind-mount it in
# docker-compose.prod.yml: replace `- certbot-www:/var/www/certbot:ro` (and the certbot
# service's `- certbot-www:/var/www/certbot`) with `- ./certbot-www:/var/www/certbot`,
# then `docker compose -f docker-compose.prod.yml up -d --force-recreate nginx certbot`.
# See the runbook for the exact diff.

set -eu

DOMAIN=""
WEBROOT="/opt/bravada/certbot-www"
DEPLOY_DIR="/opt/bravada"
EMAIL=""

usage() { sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2;;
    --webroot) WEBROOT="$2"; shift 2;;
    --email) EMAIL="$2"; shift 2;;
    -h|--help) usage 0;;
    *) echo "unknown arg: $1" >&2; usage 1;;
  esac
done

[ -n "$DOMAIN" ] || { echo "ERROR: --domain is required" >&2; usage 1; }
[ -d "$WEBROOT" ] || { echo "ERROR: webroot '$WEBROOT' does not exist. Create it (mkdir -p) and ensure nginx serves /.well-known/acme-challenge/ from it." >&2; exit 1; }
command -v docker >/dev/null || { echo "ERROR: docker not found on PATH" >&2; exit 1; }

# 1. Ensure certbot is installed (Debian/Ubuntu).
if ! command -v certbot >/dev/null 2>&1; then
  echo "==> Installing certbot ..."
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update -y && apt-get install -y certbot
  else
    echo "ERROR: certbot not installed and apt-get unavailable. Install certbot manually." >&2
    exit 1
  fi
fi

# 2. Install the renew deploy-hook that syncs the cert into ssl/ and reloads nginx.
HOOK_DIR="/etc/letsencrypt/renewal-hooks/deploy"
HOOK="$HOOK_DIR/bravada-nginx-sync.sh"
echo "==> Installing renewal deploy-hook -> $HOOK"
mkdir -p "$HOOK_DIR"
cat > "$HOOK" <<EOF
#!/bin/sh
# Auto-generated by setup_letsencrypt_autorenew.sh — syncs a renewed LE cert into
# the nginx ssl dir and gracefully reloads nginx. Runs after each successful renew.
set -eu
SSL_DIR="${DEPLOY_DIR}/ssl"
RENEWED_LINEAGE="\${RENEWED_LINEAGE:-}"
[ -n "\$RENEWED_LINEAGE" ] || { echo "bravada-nginx-sync: RENEWED_LINEAGE unset, skipping" >&2; exit 0; }
mkdir -p "\$SSL_DIR"
cp -fL "\$RENEWED_LINEAGE/fullchain.pem" "\$SSL_DIR/fullchain.pem"
cp -fL "\$RENEWED_LINEAGE/privkey.pem"   "\$SSL_DIR/privkey.pem"
chmod 644 "\$SSL_DIR/fullchain.pem"
chmod 600 "\$SSL_DIR/privkey.pem"
# Graceful nginx reload (no downtime). Try compose first, then bare container name.
cd "${DEPLOY_DIR}" && docker compose -f docker-compose.prod.yml kill -s HUP nginx 2>/dev/null \\
  || docker kill -s HUP "\$(docker ps -qf name=nginx)" 2>/dev/null \\
  || echo "bravada-nginx-sync: could not reload nginx — manual reload needed" >&2
echo "bravada-nginx-sync: synced + reloaded nginx for \$RENEWED_LINEAGE"
EOF
chmod 755 "$HOOK"

# 3. Issue the cert via webroot if not already present (idempotent).
LIVE_DIR="/etc/letsencrypt/live/${DOMAIN}"
if [ -f "$LIVE_DIR/fullchain.pem" ]; then
  echo "==> Cert already present at $LIVE_DIR — skipping issuance."
else
  echo "==> Issuing cert for ${DOMAIN} (and www.${DOMAIN}) via webroot ${WEBROOT} ..."
  EMAIL_ARG=""
  [ -n "$EMAIL" ] && EMAIL_ARG="-m ${EMAIL}"
  certbot certonly --webroot -w "$WEBROOT" \
    -d "$DOMAIN" -d "www.${DOMAIN}" \
    $EMAIL_ARG --non-interactive --agree-tos --keep-until-expiring
fi

# 4. Ensure the systemd renewal timer is enabled (certbot.timer ships with the apt pkg).
if command -v systemctl >/dev/null 2>&1; then
  systemctl enable --now certbot.timer 2>/dev/null && echo "==> certbot.timer enabled" \
    || echo "WARN: could not enable certbot.timer (manage renewal scheduling manually)"
else
  echo "WARN: systemctl not found — ensure 'certbot renew' runs at least monthly (cron)."
fi

cat <<DONE

==> DONE. Verify:
   certbot certificates                       # check notAfter (~+90d)
   ls -l ${DEPLOY_DIR}/ssl/fullchain.pem      # synced copy
   systemctl list-timers certbot.timer        # next renewal run
   echo Q | openssl s_client -connect ${DOMAIN}:443 -servername ${DOMAIN} | openssl x509 -noout -issuer -dates

Dry-run a renewal (deploys the hook, reloads nginx):
   certbot renew --dry-run
DONE
